import { PGlite } from "@electric-sql/pglite";
import { readFile } from "node:fs/promises";
import assert from "node:assert/strict";
const db = new PGlite();
await db.exec(`create role anon; create role authenticated;
create schema auth; create table auth.users(id uuid primary key);
create function auth.uid() returns uuid language sql as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
grant usage on schema auth to authenticated; grant execute on function auth.uid() to authenticated;`);
await db.exec(await readFile(new URL('../supabase/migrations/202609220001_customer_accounts.sql', import.meta.url), 'utf8'));
const alice = '11111111-1111-4111-8111-111111111111';
const bob = '22222222-2222-4222-8222-222222222222';
await db.query('insert into auth.users values ($1),($2)', [alice,bob]);
await db.query("select set_config('request.jwt.claim.sub',$1,false)",[alice]);
await db.exec('set role authenticated');
await db.query("insert into public.customer_profiles(user_id,name) values ($1,'Alice')",[alice]);
await assert.rejects(db.query("insert into public.customer_profiles(user_id,name) values ($1,'Bob')",[bob]), /row-level security/);
await db.query("update public.customer_profiles set name='Alice updated' where user_id=$1",[alice]);
assert.equal((await db.query('select name from public.customer_profiles')).rows[0].name,'Alice updated');
await assert.rejects(db.query('update public.customer_profiles set user_id=$1',[bob]), /permission denied/);
await db.exec('reset role');
await db.query("select set_config('request.jwt.claim.sub',$1,false)",[bob]);
await db.exec('set role authenticated');
assert.equal((await db.query('select * from public.customer_profiles')).rows.length,0);
assert.equal((await db.query("update public.customer_profiles set name='Hacked' returning user_id")).rows.length,0);
await assert.rejects(db.query('delete from public.customer_profiles'), /permission denied/);
await db.exec('reset role; set role anon');
await assert.rejects(db.query('select * from public.customer_profiles'), /permission denied/);
await db.close();
console.log('Customer profile isolation, ownership and anonymous-access tests passed.');
